import * as fs from "node:fs";
import * as path from "node:path";
import { describe, expect, it } from "vitest";

import { startFakeOpenCloudServerAsync } from "#test/e2e/cli/fake-open-cloud.ts";
import {
	buildPassingJestOutput,
	createFixtureSandbox,
	createOpenCloudEnvironment,
	rojoOnPath,
	runCliAsync,
} from "#test/e2e/cli/helpers.ts";
import { nodeAt, readPlaceTree } from "#test/e2e/cli/place-tree.ts";

const USER_AUTHORED_FIXTURE_PATH = path.resolve(__dirname, "../fixtures/user-authored-config");
const RUN_TIMEOUT_MS = 60_000;
const STUB_MARKER = "-- Auto-generated by jest-roblox (do not edit)\n";

describe("multi-project user-authored config replacement", () => {
	it.skipIf(!rojoOnPath())(
		"should stage a generated stub in place of a user-authored jest.config.luau and leave the user file untouched",
		async () => {
			expect.assertions(6);

			const sandbox = createFixtureSandbox(USER_AUTHORED_FIXTURE_PATH);
			const configPath = path.join(sandbox, "jest.config.ts");
			fs.writeFileSync(
				configPath,
				fs.readFileSync(configPath, "utf-8").replace('"game.rbxl"', '"game.rbxlx"'),
			);
			const userConfigPath = path.join(sandbox, "src/b/jest.config.luau");
			const seededUserConfig = fs.readFileSync(userConfigPath);

			const server = await startFakeOpenCloudServerAsync([
				{ jestOutput: buildPassingJestOutput(), pkg: "a", project: "a" },
				{ jestOutput: buildPassingJestOutput(), pkg: "b", project: "b" },
			]);

			const result = await runCliAsync(["--backend", "open-cloud", "--parallel=2"], {
				cwd: sandbox,
				env: createOpenCloudEnvironment(server.baseUrl),
				timeoutMs: RUN_TIMEOUT_MS,
			});

			expect(result.exitCode, `stderr: ${result.stderr}\nstdout: ${result.stdout}`).toBe(0);
			expect(fs.readFileSync(userConfigPath).equals(seededUserConfig)).toBeTrue();

			const cacheStub = fs.readFileSync(
				path.join(sandbox, ".jest-roblox/cache/src/b/jest.config.luau"),
				"utf-8",
			);

			expect(cacheStub).toStartWith(STUB_MARKER);
			expect(cacheStub).toContain('\tdisplayName = "b",\n');

			const placeFile = path.join(sandbox, "game.rbxlx");
			const mount = nodeAt(readPlaceTree(placeFile), ["ReplicatedStorage", "B"]);

			expect(mount.children.filter((node) => node.name === "jest.config")).toHaveLength(1);
			expect(fs.readFileSync(placeFile, "utf-8")).not.toContain("b-user");
		},
		RUN_TIMEOUT_MS + 5000,
	);
});
