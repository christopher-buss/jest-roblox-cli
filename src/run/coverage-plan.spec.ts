import { fromAny } from "@total-typescript/shoehorn";

import { describe, expect, it } from "vitest";

import { createMemoryFileSystem } from "#test/mocks/memory-file-system.ts";
import { createResolvedConfig } from "#test/mocks/resolved-config.ts";
import { buildProjectCoveragePlan } from "./coverage-plan.ts";

describe(buildProjectCoveragePlan, () => {
	it.for([undefined, ["src/selected.ts"]])(
		"should preserve the configured coverage universe %j with type-test globs",
		(collectCoverageFrom) => {
			expect.assertions(1);

			const { fileSystem } = createMemoryFileSystem();
			const result = buildProjectCoveragePlan({
				cacheRoot: "/cache",
				fileSystem,
				projects: [fromAny({ include: ["src/client/**/*.spec-d.ts"] })],
				rootConfig: createResolvedConfig({ collectCoverage: true, collectCoverageFrom }),
			});

			expect(result.coverageInclude).toStrictEqual(collectCoverageFrom);
		},
	);

	it("should pair bake ownership with files written into the shadow", () => {
		expect.assertions(3);

		const stub = "-- Auto-generated by jest-roblox (do not edit)\nreturn {}\n";
		const { fileSystem, volume } = createMemoryFileSystem({
			"/cache/out/client/jest.config.luau": stub,
		});
		const result = buildProjectCoveragePlan({
			cacheRoot: "/cache",
			fileSystem,
			projects: [
				fromAny({
					include: ["src/client/**/*.spec.ts"],
					rojoMounts: [
						{ dataModelPath: "ReplicatedStorage/client", fsPath: "out/client" },
					],
				}),
			],
			rootConfig: createResolvedConfig({ collectCoverage: true }),
		});
		const shadow = {
			isShadowed: () => true,
			mountedDirectory: () => "/shadow/client",
			root: "/shadow",
		};

		expect(result.bake.run(shadow)).toBeTrue();
		expect(volume.readFileSync("/shadow/client/jest.config.luau", "utf8")).toBe(stub);
		expect(result.bake.isBakeOwned("/shadow/client/jest.config.luau")).toBeTrue();
	});
});
