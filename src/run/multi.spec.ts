function setupDefaults(configOverrides: Partial<ResolvedConfig> = {}) {
	const { fileSystem, volume } = createMemoryFileSystem();
	const config = makeConfig(configOverrides);

	mocks = createRunMocks();
	seams = toSeams(mocks);

	mocks.resolveAllProjects.mockResolvedValue([
		makeResolvedProject({ displayName: "client", outDir: "out/client" }),
		makeResolvedProject({
			displayName: "server",
			include: ["src/server/**/*.spec.ts"],
			outDir: "out/server",
			rojoMounts: [{ dataModelPath: "ServerScriptService/server", fsPath: "out/server" }],
		}),
	]);
	mocks.createSetupResolver.mockReturnValue((input) => input);
	mocks.execFile.mockImplementation((_file, args, _options, callback) => {
		const outputPath = String(args[3]);
		volume.mkdirSync(path.dirname(outputPath), { recursive: true });
		volume.writeFileSync(outputPath, "RBXL");
		callback(null, "", "");
	});
	mocks.prepareCoverage.mockResolvedValue(fromAny(makeCoverageResult()));
	mocks.resolveBackend.mockResolvedValue(makeBackend("studio"));
	mocks.runProjects.mockImplementation(async (input) => {
		return {
			backendTiming: { executionMs: 100, uploadMs: 50 },
			ranProjectIndices: allProjectIndices(input),
			results: input.projects.map(() => makeExecuteResult()),
		};
	});
	mocks.tsconfigReader.mockReturnValue(
		fromAny({
			config: { compilerOptions: { outDir: "out", rootDir: "src" } },
			path: "/test/tsconfig.json",
		}),
	);
	writeRojoProject(volume);

	return { config, fileSystem, volume };
}

function seedProjectFiles(volume: MemoryVolume): void {
	volume.mkdirSync("/test/src/client", { recursive: true });
	volume.writeFileSync("/test/src/client/a.spec.ts", "");
	volume.mkdirSync("/test/src/server", { recursive: true });
	volume.writeFileSync("/test/src/server/b.spec.ts", "");
}

function seedUserAuthoredConfigs(volume: MemoryVolume): void {
	for (const mount of ["out/client", "out/server"]) {
		volume.mkdirSync(path.resolve("/test", mount), { recursive: true });
		volume.writeFileSync(path.resolve("/test", mount, STUB_FILENAME), "return {}\n");
	}
}

