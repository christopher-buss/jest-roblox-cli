	it("should take the mounts inside a code root out of the place", async () => {
		expect.assertions(2);

		const { config, fileSystem, volume } = setupDefaults();
		writeStagedMount(volume);
		mocks.resolveBackend.mockResolvedValueOnce(makeBackend("open-cloud"));
		seedProjectFiles(volume);

		await runMultiProjectAsync({
			cli: makeCli(),
			config,
			fileSystem,
			rawProjects: [makeProjectEntry("client")],
			seams,
		});

		const bundle = bundleSchema.assert(
			JSON.parse(String(volume.readFileSync(bundleFile(config), "utf8"))),
		);

		// Every mount here resolves inside a Code Root: the compiled output
		// each project declares, the generated stub beneath it, and the one
		// under the staging directory.
		expect(bundle.mounts.map((mount) => mount.dataModelPath)).toStrictEqual([
			["ReplicatedStorage", "Mount"],
			["ReplicatedStorage", "client"],
			["ServerScriptService", "server"],
			["ReplicatedStorage", "client", "jest.config"],
			["ServerScriptService", "server", "jest.config"],
		]);
		// They all went into the bundle, so the harness project declares nothing
		// under either service — the services themselves stay, because rojo
		// builds one whether or not the project puts anything there.
		expect(writtenSynthProject(volume).tree).toStrictEqual({
			$className: "DataModel",
			ReplicatedStorage: {},
			ServerScriptService: {},
		});
	});

