function recordingTimingCollector() {
	const asyncNames: Array<string> = [];
	const names: Array<string> = [];
	const records: Array<{ elapsedMs: number; name: string }> = [];
	const timing: TimingCollector = {
		enabled: true,
		flushTimingReport: () => {
			/* unused */
		},
		profile: (name, func) => {
			names.push(name);
			return func();
		},
		profileAsync: async (name, func) => {
			asyncNames.push(name);
			return func();
		},
		profileTimed: (name, func) => {
			names.push(name);
			return { elapsedMs: 0, value: func() };
		},
		profileTimedAsync: async (name, func) => {
			asyncNames.push(name);
			return { elapsedMs: 0, value: await func() };
		},
		record: (name, elapsedMs) => {
			records.push({ name, elapsedMs });
		},
	};
	return { asyncNames, names, records, timing };
}

function writeRojoProject(volume: MemoryVolume): void {
	const tree = {
		$className: "DataModel",
		ReplicatedStorage: { client: { $path: "out/client" } },
		ServerScriptService: { server: { $path: "out/server" } },
	};
	volume.mkdirSync("/test/out/client", { recursive: true });
	volume.mkdirSync("/test/out/server", { recursive: true });
	volume.writeFileSync("/test/default.project.json", JSON.stringify({ name: "test", tree }));
}

