/**
 * Complete every job in the fake executor.
 * @param input - Jobs and the dispatch clock.
 * @param input.jobs - Selected runtime jobs.
 * @param input.startTime - Start of the dispatch window.
 * @returns Results identified by job index.
 */
function allJobResults(input: {
	jobs: ReadonlyArray<ConfiguredJob>;
	startTime: number;
}): Array<ExecuteResult & { jobIndex: number }> {
	return input.jobs.map((job, jobIndex) => {
		return {
			...makeExecuteResult({
				result: makeJestResult({ numTotalTests: job.testFiles.length }),
				timing: {
					executionMs: 100,
					startTime: input.startTime,
					testsMs: 50,
					totalMs: 200,
					uploadMs: 50,
				},
			}),
			jobIndex,
		};
	});
}

function captureText(stream: typeof process.stderr | typeof process.stdout) {
	const chunks: Array<string> = [];
	vi.spyOn(stream, "write").mockImplementation((chunk) => {
		chunks.push(String(chunk));
		return true;
	});
	return () => chunks.join("");
}

function runRuntimeCatalog(files: Array<string>): void {
	mocks.runProjects.mockImplementation(async ({ jobs, startTime }) => {
		return {
			backendTiming: { executionMs: 0 },
			results: jobs.map((job, jobIndex) => {
				const pattern = new RegExp(String(job.argv.testPathPattern ?? ""));
				const matched = files.filter((file) => pattern.test(file));
				return {
					...makeExecuteResult({
						result: makeJestResult({
							numTotalTests: matched.length,
							testResults: matched.map((testFilePath) => {
								return {
									gaps: {},
									numFailingTests: 0,
									numPassingTests: 1,
									numPendingTests: 0,
									testFilePath,
									testResults: [],
								};
							}),
						}),
						timing: { executionMs: 0, startTime, testsMs: 0, totalMs: 0 },
					}),
					jobIndex,
				};
			}),
		};
	});
}

function runVmSessions(): void {
	mocks.runProjects.mockImplementation(async (input) => {
		const vmCount = input.vmParallel === "auto" ? input.jobs.length : (input.vmParallel ?? 1);
		return {
			backendTiming: { executionMs: 0 },
			results: allJobResults(input).map((execution, index) => {
				return { ...execution, gameOutput: `vm ${index % vmCount}` };
			}),
		};
	});
}

function runtimeConfigs(initial: Array<[string, string]> = []): Map<string, string> {
	const configs = new Map(initial);
	mocks.runProjects.mockImplementation(async (input) => {
		for (const job of input.jobs) {
			for (const mount of job.runtimeInjectionPaths!) {
				configs.set(mount, "generated");
			}
		}

		return { backendTiming: { executionMs: 0 }, results: allJobResults(input) };
	});
	return configs;
}

