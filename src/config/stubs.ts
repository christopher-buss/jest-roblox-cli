interface SyncMountStubResult {
	changed: boolean;
	targetPath: string | undefined;
}

const HEADER = "-- Auto-generated by jest-roblox (do not edit)\n";

export const STUB_FILENAME = "jest.config.luau";

/**
 * Distinguishes own-stubs (safe to delete) from user-authored configs.
 * Reads only the first `HEADER.length` bytes — bounded I/O regardless of
 * file size. Used by workspace pre-flight cleanup and the coverage shadow
 * orphan-sweep to ensure neither ever removes a user's canonical config.
 */
export function isGeneratedStub(
	filePath: string,
	fileSystem: FileSystem = nodeFileSystem,
): boolean {
	try {
		const fd = fileSystem.openSync(filePath, "r");
		try {
			const buffer = Buffer.alloc(HEADER.length);
			fileSystem.readSync(fd, buffer, 0, HEADER.length, 0);
			return buffer.toString("utf8") === HEADER;
		} finally {
			fileSystem.closeSync(fd);
		}
	} catch {
		// Defensive catch for unusual FS errors (permission denied,
		// EISDIR, etc.). Caller treats `false` as "not our stub".
		return false;
	}
}

const LEGACY_LUA_FILENAME = "jest.config.lua";

/**
 * Both names rojo merges into one `jest.config` ModuleScript. The bake writes
 * only the `.luau`, but every sweep has to see the legacy `.lua` too, or an
 * upgraded shadow keeps a stub beside the one that replaced it.
 */
const STUB_FILENAMES: ReadonlySet<string> = new Set([LEGACY_LUA_FILENAME, STUB_FILENAME]);

/**
 * The bake half of a coverage prepare: mirror this run's cache stubs into the
 * shadow, and declare them so the shadow's orphan sweeps leave them be. See
 * {@link ShadowBake} for why the two travel as one.
 */
export function createStubBake({
	cacheRoot,
	fileSystem = nodeFileSystem,
	projects,
}: {
	readonly cacheRoot: string;
	readonly fileSystem?: FileSystem;
	readonly projects: Array<ResolvedProjectConfig>;
}): ShadowBake {
	return {
		isBakeOwned: (shadowPath) => isBakedStub(fileSystem, shadowPath),
		run: (shadow) => {
			return syncStubsToShadowDirectory({
				fileSystem,
				projects,
				rootDirectory: cacheRoot,
				shadow,
			});
		},
	};
}

/**
 * The bake's own writes, as the shadow sees them. A user-authored config is
 * not one: it reaches the shadow through the mirror, which makes the sweeps
 * judge it by its source twin like any other copied file.
 */
function isBakedStub(fileSystem: FileSystem, shadowPath: string): boolean {
	return STUB_FILENAMES.has(path.basename(shadowPath)) && isGeneratedStub(shadowPath, fileSystem);
}

const SKIP_FIELDS: ReadonlySet<string> = new Set(["exclude", "include"]);

type StubConfig = Partial<UndefinedTolerant<ProjectTestConfig>>;

export function serializeToLuau(config: StubConfig): string {
	let output = `${HEADER}return {\n`;

	const robloxConfig = {
		...config,
		testPathIgnorePatterns: toRobloxTestPathIgnorePatterns(config.testPathIgnorePatterns),
	};
	for (const [key, value] of Object.entries(robloxConfig)) {
		if (SKIP_FIELDS.has(key)) {
			continue;
		}

		if (value === undefined) {
			continue;
		}

		const serialized = serializeLuauValue(
			key === "testMatch" && Array.isArray(value)
				? toRobloxTestMatch(value.filter(isString))
				: value,
		);

		output += `\t${key} = ${serialized},\n`;
	}

	output += "}\n";
	return output;
}

export function generateProjectConfigs(
	projects: Array<{ config: StubConfig; outputPath: string }>,
	fileSystem: FileSystem = nodeFileSystem,
): void {
	for (const project of projects) {
		const directory = path.dirname(project.outputPath);
		if (hasUserAuthoredConfig(directory, fileSystem)) {
			continue;
		}

		const content = serializeToLuau(project.config);
		fileSystem.mkdirSync(directory, { recursive: true });
		fileSystem.writeFileSync(project.outputPath, content, "utf8");

		if (path.basename(project.outputPath) === STUB_FILENAME) {
			removeLegacyGeneratedStub(fileSystem, directory);
		}
	}
}

// These project-level values are unwanted in the runtime stub:
// `outDir`/`root` are reconstructed per mount and Type Tests only run on the
// host. `displayName` and `include` are overwritten downstream, while
// `include`/`exclude` are dropped by `serializeToLuau`, so filtering those here
// would be redundant.
const STUB_SKIP_KEYS: ReadonlySet<string> = new Set([
	"outDir",
	// Host-only budget our own runner enforces around `Jest.runCLI`; it
	// reaches the runtime on the argv instead, and Jest would reject it here.
	"projectTimeout",
	"root",
	"typecheck",
]);

/** The two trees a stub pass reads and writes, and what reaches them. */
interface StubRoots {
	fileSystem: FileSystem;
	rootDirectory: string;
	writeRoot: string;
}

/** The shadow a stub is synced into, and the source tree it is read from. */
interface SyncTarget {
	fileSystem: FileSystem;
	rootDirectory: string;
	shadow: ShadowLayout;
}

/**
 * True when the mount directory contains a non-marker `jest.config.luau` —
 * i.e. a user-authored config Rojo will sync. Source of truth for whether
 * to skip generating a stub at that mount. Used by `generateProjectStubs`,
 * `cleanLeftoverStubs`'s callers, and the multi-project + workspace runners
 * when deciding stub-write and runtime-injection eligibility.
 */
export function hasUserAuthoredConfig(
	directoryPath: string,
	fileSystem: FileSystem = nodeFileSystem,
): boolean {
	// A `.luau` or legacy `.lua` may be either our generated stub or a
	// user-authored config; only the HEADER prefix distinguishes them.
	// Reuse `isGeneratedStub`'s bounded header-read so this detection
	// check stays cheap (a few bytes) and resilient — unusual FS errors
	// downgrade to "not user-authored" rather than throwing out of a
	// detection helper called from multiple cleanup/build paths.
	const luauPath = path.join(directoryPath, STUB_FILENAME);
	if (fileSystem.existsSync(luauPath) && !isGeneratedStub(luauPath, fileSystem)) {
		return true;
	}

	const luaPath = path.join(directoryPath, LEGACY_LUA_FILENAME);
	return fileSystem.existsSync(luaPath) && !isGeneratedStub(luaPath, fileSystem);
}

/**
 * For a multi-mount project, the stubs-per-mount rule requires that a
 * user-authored config at any tracked FS path must appear at every tracked
 * FS path (or none). Throws `ConfigError` when the project has partial
 * coverage — some mounts have a user config and others don't.
 */
export function assertStubCollisionRule({
	fileSystem = nodeFileSystem,
	project,
	rootDirectory,
}: {
	readonly fileSystem?: FileSystem;
	readonly project: ResolvedProjectConfig;
	readonly rootDirectory: string;
}): void {
	const withUser: Array<string> = [];
	const withoutUser: Array<string> = [];

	for (const mount of project.rojoMounts) {
		assertMountContained({ fsPath: mount.fsPath, project, rootDirectory });

		const absolute = path.resolve(rootDirectory, mount.fsPath);
		if (hasUserAuthoredConfig(absolute, fileSystem)) {
			withUser.push(mount.fsPath);
		} else {
			withoutUser.push(mount.fsPath);
		}
	}

	if (withUser.length === 0 || withoutUser.length === 0) {
		return;
	}

	const withUserList = withUser.join(", ");
	const withoutUserList = withoutUser.join(", ");
	throw new ConfigError(
		`Project "${project.displayName}": user-authored jest config present at some mounts but not others.\n\n` +
			`With user config: ${withUserList}\n` +
			`Without user config: ${withoutUserList}\n\n` +
			"For multi-mount projects, either every tracked mount must have a user config, or none.",
	);
}

/**
 * Pre-flight cleanup of marker-bearing leftover stubs at known mount paths.
 * Walks O(mounts), no recursive scan. Returns the cleaned paths so callers
 * can surface a `stderr` notice.
 *
 * Containment is enforced at two layers because either alone has a hole:
 * - `assertMountContained` rejects absolute paths and `..`-escapes lexically
 *   (Rojo-derived mounts can carry `..` segments when `resolveNestedProjects`
 *   relocates a path).
 * - `path.relative` against the realpath-resolved root catches symlinked
 *   mount directories pointing outside the package root. Platform-correct —
 *   it honours only the OS's separator, so a POSIX filename literally
 *   containing `\` doesn't pass as if it were a Windows escape.
 */
export function cleanLeftoverStubs({
	fileSystem = nodeFileSystem,
	projects,
	rootDirectory,
}: {
	readonly fileSystem?: FileSystem;
	readonly projects: Array<ResolvedProjectConfig>;
	readonly rootDirectory: string;
}): Array<string> {
	const cleaned: Array<string> = [];
	let realRoot: string | undefined;
	function realRootResolved(): string {
		realRoot ??= fileSystem.realpathSync(path.resolve(rootDirectory));
		return realRoot;
	}

	for (const project of projects) {
		cleaned.push(
			...cleanLeftoverStubsForProject({
				fileSystem,
				project,
				realRootResolved,
				rootDirectory,
			}),
		);
	}

	return cleaned;
}

export function generateProjectStubs({
	fileSystem = nodeFileSystem,
	outputRoot,
	projects,
	rootDirectory,
}: {
	readonly fileSystem?: FileSystem;
	readonly outputRoot?: string | undefined;
	readonly projects: Array<ResolvedProjectConfig>;
	readonly rootDirectory: string;
}): void {
	const writeRoot = outputRoot ?? rootDirectory;
	const entries: Array<{ config: StubConfig; outputPath: string }> = [];

	for (const project of projects) {
		assertStubCollisionRule({ fileSystem, project, rootDirectory });

		const stubConfig: StubConfig = {
			...buildStubConfig(project.config),
			displayName: project.displayName,
			testMatch: project.testMatch,
		};

		entries.push(
			...buildStubEntriesForProject({
				fileSystem,
				project,
				rootDirectory,
				stubConfig,
				writeRoot,
			}),
		);
	}

	generateProjectConfigs(entries, fileSystem);
}

export function syncStubsToShadowDirectory({
	fileSystem = nodeFileSystem,
	projects,
	rootDirectory,
	shadow,
}: {
	readonly fileSystem?: FileSystem;
	readonly projects: Array<ResolvedProjectConfig>;
	readonly rootDirectory: string;
	readonly shadow: ShadowLayout;
}): boolean {
	let hasChanged = false;
	const expectedPaths = new Set<string>();
	const target = { fileSystem, rootDirectory, shadow };

	for (const project of projects) {
		for (const mount of project.rojoMounts) {
			const result = syncMountStub({ ...target, fsPath: mount.fsPath, project });
			if (result.targetPath !== undefined) {
				expectedPaths.add(result.targetPath);
			}

			hasChanged ||= result.changed;
		}
	}

	for (const existing of findShadowStubs(fileSystem, shadow.root)) {
		if (expectedPaths.has(existing)) {
			continue;
		}

		// `prepareCoverage` mirrors the source tree into the shadow before
		// this hook runs, so a user's authored `jest.config.luau` (e.g.
		// compiled from `src/shared/jest.config.ts`) may land here. The
		// orphan sweep is only allowed to delete generated stubs we own —
		// anything bearing the marker. User configs must survive into the
		// coverage place.
		if (!isGeneratedStub(existing, fileSystem)) {
			continue;
		}

		fileSystem.unlinkSync(existing);
		removeEmptyParents({ directory: path.dirname(existing), fileSystem, stopAt: shadow.root });
		hasChanged = true;
	}

	return hasChanged;
}

/**
 * Refuse to let any downstream write land outside `rootDirectory`. Mount
 * fsPaths originate from the rojo tree and `resolveNestedProjects` can emit
 * values with `..` segments (nested projects relocate paths); combined with
 * `path.resolve` on Windows, a permissive fsPath could send stub writes to
 * `D:\outside\...`. Guard at every write-site.
 */
function assertMountContained({
	fsPath,
	project,
	rootDirectory,
}: {
	readonly fsPath: string;
	readonly project: ResolvedProjectConfig;
	readonly rootDirectory: string;
}): void {
	if (path.isAbsolute(fsPath)) {
		throw new Error(
			`Project "${project.displayName}" mount fsPath must be relative, got: ${fsPath}`,
		);
	}

	const rootResolved = path.resolve(rootDirectory);
	const mountResolved = path.resolve(rootDirectory, fsPath);
	if (mountResolved !== rootResolved && !mountResolved.startsWith(rootResolved + path.sep)) {
		throw new Error(
			`Project "${project.displayName}" mount fsPath escapes root directory: ${fsPath}`,
		);
	}
}

function cleanLeftoverStubsForProject({
	fileSystem,
	project,
	realRootResolved,
	rootDirectory,
}: {
	readonly fileSystem: FileSystem;
	readonly project: ResolvedProjectConfig;
	readonly realRootResolved: () => string;
	readonly rootDirectory: string;
}): Array<string> {
	const cleaned: Array<string> = [];
	for (const mount of project.rojoMounts) {
		assertMountContained({ fsPath: mount.fsPath, project, rootDirectory });
		const stubPath = path.resolve(rootDirectory, mount.fsPath, STUB_FILENAME);
		if (!isGeneratedStub(stubPath, fileSystem)) {
			continue;
		}

		const realStubPath = fileSystem.realpathSync(stubPath);
		const root = realRootResolved();
		const relativePath = path.relative(root, realStubPath);
		const isInRoot = !relativePath.startsWith("..") && !path.isAbsolute(relativePath);
		if (!isInRoot) {
			throw new Error(
				`Project "${project.displayName}" mount fsPath resolves outside root via symlink: ${mount.fsPath} → ${realStubPath}`,
			);
		}

		fileSystem.unlinkSync(stubPath);
		cleaned.push(stubPath);
	}

	return cleaned;
}

function buildStubEntriesForProject({
	fileSystem,
	project,
	rootDirectory,
	stubConfig,
	writeRoot,
}: StubRoots & {
	readonly project: ResolvedProjectConfig;
	readonly stubConfig: StubConfig;
}): Array<{ config: StubConfig; outputPath: string }> {
	const entries: Array<{ config: StubConfig; outputPath: string }> = [];
	for (const mount of project.rojoMounts) {
		// Per-mount FS check — skip generation when a non-marker
		// `jest.config.luau` already exists at the mount on disk.
		// A schema-level "is this a user-authored project" hint is
		// not enough: a TS string-entry whose compile hasn't run
		// yet still needs a generated stub for the mount.
		const sourceMount = path.resolve(rootDirectory, mount.fsPath);
		if (hasUserAuthoredConfig(sourceMount, fileSystem)) {
			continue;
		}

		const outputPath = path.resolve(writeRoot, mount.fsPath, STUB_FILENAME);
		entries.push({ config: stubConfig, outputPath });
	}

	return entries;
}

function buildStubConfig(config: ResolvedConfig): Partial<ProjectTestConfig> {
	const result: Partial<ProjectTestConfig> = {};
	for (const [key, value] of Object.entries(config)) {
		if (PROJECT_TEST_KEYS.has(key) && !STUB_SKIP_KEYS.has(key)) {
			Reflect.set(result, key, value);
		}
	}

	return result;
}

function syncMountStub({
	fileSystem,
	fsPath,
	project,
	rootDirectory,
	shadow,
}: SyncTarget & {
	readonly fsPath: string;
	readonly project: ResolvedProjectConfig;
}): SyncMountStubResult {
	assertMountContained({ fsPath, project, rootDirectory });

	const sourcePath = path.resolve(rootDirectory, fsPath, STUB_FILENAME);
	if (!fileSystem.existsSync(sourcePath)) {
		return { changed: false, targetPath: undefined };
	}

	// Asked rather than joined onto the shadow root: a mount the coverage
	// narrowing demoted is served from its spine copy, and a stub baked into
	// the mirror beside it would be in a directory the place never mounts.
	const targetPath = path.resolve(shadow.mountedDirectory(fsPath), STUB_FILENAME);
	const sourceContent = fileSystem.readFileSync(sourcePath);

	if (fileSystem.existsSync(targetPath)) {
		const targetContent = fileSystem.readFileSync(targetPath);
		if (Buffer.compare(sourceContent, targetContent) === 0) {
			return { changed: false, targetPath };
		}
	}

	fileSystem.mkdirSync(path.dirname(targetPath), { recursive: true });
	fileSystem.copyFileSync(sourcePath, targetPath);
	return { changed: true, targetPath };
}

function* findShadowStubs(fileSystem: FileSystem, directory: string): Generator<string, void> {
	if (!fileSystem.existsSync(directory)) {
		return;
	}

	const entries = fileSystem.readdirSync(directory, { withFileTypes: true });
	for (const entry of entries) {
		const fullPath = path.resolve(directory, entry.name);
		if (entry.isDirectory()) {
			yield* findShadowStubs(fileSystem, fullPath);
		} else if (STUB_FILENAMES.has(entry.name)) {
			yield fullPath;
		}
	}
}

function removeEmptyParents({
	directory,
	fileSystem,
	stopAt,
}: {
	readonly directory: string;
	readonly fileSystem: FileSystem;
	readonly stopAt: string;
}): void {
	const resolved = path.resolve(directory);
	const resolvedStop = path.resolve(stopAt);
	if (resolved === resolvedStop || !resolved.startsWith(resolvedStop)) {
		return;
	}

	try {
		fileSystem.rmdirSync(resolved);
		removeEmptyParents({ directory: path.dirname(resolved), fileSystem, stopAt });
	} catch {
		// Best-effort cleanup
	}
}

// Rojo merges `jest.config.lua` and `jest.config.luau` into the same
// ModuleScript name, so leaving an old generated `.lua` stub next to the
// new `.luau` would cause a name collision after upgrade. Caller guarantees
// (via `hasUserAuthoredConfig`) that any `.lua` present here is our own
// HEADER-prefixed stub, not a user-authored file.
function removeLegacyGeneratedStub(fileSystem: FileSystem, directoryPath: string): void {
	const legacyPath = path.join(directoryPath, LEGACY_LUA_FILENAME);
	if (fileSystem.existsSync(legacyPath)) {
		fileSystem.unlinkSync(legacyPath);
	}
}

function escapeString(value: string): string {
	return value
		.replace(/\\/g, "\\\\")
		.replace(/"/g, '\\"')
		.replace(/\n/g, "\\n")
		.replace(/\r/g, "\\r")
		.replace(/\t/g, "\\t");
}

function serializeLuauValue(value: unknown): string {
	if (typeof value === "string") {
		return `"${escapeString(value)}"`;
	}

	if (Array.isArray(value)) {
		const items = value.map((item: unknown) => serializeLuauValue(item));
		return `{ ${items.join(", ")} }`;
	}

	if (typeof value === "object" && value !== null) {
		const entries = Object.entries(value)
			.filter(([, propertyValue]) => propertyValue !== undefined)
			.map(([key, propertyValue]) => `${key} = ${serializeLuauValue(propertyValue)}`);
		return `{ ${entries.join(", ")} }`;
	}

	return String(value);
}
