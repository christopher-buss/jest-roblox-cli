import { fromAny } from "@total-typescript/shoehorn";

import { describe, expect, it } from "vitest";

import { createMemoryFileSystem } from "#test/mocks/memory-file-system.ts";
import { createResolvedConfig } from "#test/mocks/resolved-config.ts";
import { makeResolvedProject } from "#test/mocks/spec-resolved-project.ts";
import type { FileSystem } from "../utils/file-system.ts";
import type { ResolvedProjectConfig } from "./projects.ts";
import type { ResolvedConfig } from "./schema.ts";
import { cleanLeftoverStubs, generateProjectStubs } from "./stubs.ts";

const GENERATED = "-- Auto-generated by jest-roblox (do not edit)\n";

function mountsAt(...fsPaths: Array<string>): ResolvedProjectConfig["rojoMounts"] {
	return fsPaths.map((fsPath) => ({ dataModelPath: `ReplicatedStorage/${fsPath}`, fsPath }));
}

function writeStubs(fileSystem: FileSystem, projects: Array<ResolvedProjectConfig>): void {
	generateProjectStubs({ fileSystem, outputRoot: "/root", projects, rootDirectory: "/root" });
}

function writeCacheStubs(fileSystem: FileSystem, projects: Array<ResolvedProjectConfig>): void {
	generateProjectStubs({ fileSystem, outputRoot: "/cache", projects, rootDirectory: "/root" });
}

function generateClientStub(overrides: Partial<ResolvedConfig>): string {
	const { fileSystem, volume } = createMemoryFileSystem();
	const project = makeResolvedProject({
		config: { ...createResolvedConfig(), rootDir: "/root", ...overrides },
		rojoMounts: [{ dataModelPath: "ReplicatedStorage/Client", fsPath: "out/Client" }],
	});

	generateProjectStubs({
		fileSystem,
		outputRoot: "/root",
		projects: [project],
		rootDirectory: "/root",
	});

	return String(volume.readFileSync("/root/out/Client/jest.config.luau", "utf8"));
}

describe("stub writing", () => {
	it("should write the stub at the mount path", () => {
		expect.assertions(1);

		const { fileSystem, volume } = createMemoryFileSystem();

		writeStubs(fileSystem, [makeResolvedProject({ displayName: "client" })]);

		const content = volume.readFileSync("/root/out/client/jest.config.luau", "utf8");

		expect(content).toContain('\tdisplayName = "client",');
	});

	it("should create parent directories if they don't exist", () => {
		expect.assertions(1);

		const { fileSystem, volume } = createMemoryFileSystem();

		writeStubs(fileSystem, [makeResolvedProject({ rojoMounts: mountsAt("deep/nested/dir") })]);

		expect(volume.existsSync("/root/deep/nested/dir/jest.config.luau")).toBeTrue();
	});

	it("should skip writing when jest.config.luau already exists at the output directory", () => {
		expect.assertions(1);

		const { fileSystem, volume } = createMemoryFileSystem({
			"/cache/out/client/jest.config.luau": "return {}",
		});

		writeCacheStubs(fileSystem, [makeResolvedProject({ displayName: "client" })]);

		expect(volume.readFileSync("/cache/out/client/jest.config.luau", "utf8")).toBe("return {}");
	});

	it("should write a stub at every mount of a project", () => {
		expect.assertions(2);

		const { fileSystem, volume } = createMemoryFileSystem();

		writeStubs(fileSystem, [
			makeResolvedProject({ rojoMounts: mountsAt("out/client", "out/server") }),
		]);

		expect(volume.existsSync("/root/out/client/jest.config.luau")).toBeTrue();

		expect(volume.existsSync("/root/out/server/jest.config.luau")).toBeTrue();
	});

	it("should write a stub for every project", () => {
		expect.assertions(2);

		const { fileSystem, volume } = createMemoryFileSystem();

		writeStubs(fileSystem, [
			makeResolvedProject({ displayName: "client", rojoMounts: mountsAt("out/client") }),
			makeResolvedProject({ displayName: "server", rojoMounts: mountsAt("out/server") }),
		]);

		const client = volume.readFileSync("/root/out/client/jest.config.luau", "utf8");

		const server = volume.readFileSync("/root/out/server/jest.config.luau", "utf8");

		expect(client).toContain('\tdisplayName = "client",');
		expect(server).toContain('\tdisplayName = "server",');
	});
});

describe(generateProjectStubs, () => {
	it("should support a mount at the project root", () => {
		expect.assertions(1);

		const { fileSystem, volume } = createMemoryFileSystem();

		const project = makeResolvedProject({
			rojoMounts: [{ dataModelPath: "ReplicatedStorage", fsPath: "." }],
		});

		generateProjectStubs({
			fileSystem,
			outputRoot: "/cache/workspace",
			projects: [project],
			rootDirectory: "/root",
		});

		expect(volume.existsSync("/cache/workspace/jest.config.luau")).toBeTrue();
	});

	it("should reject a mount in a sibling directory sharing the root prefix", () => {
		expect.assertions(1);

		const { fileSystem } = createMemoryFileSystem();

		const project = makeResolvedProject({
			rojoMounts: [{ dataModelPath: "ReplicatedStorage", fsPath: "../root-backup" }],
		});

		expect(() => {
			generateProjectStubs({
				fileSystem,
				outputRoot: "/root",
				projects: [project],
				rootDirectory: "/root",
			});
		}).toThrow("mount fsPath escapes root directory");
	});

	it("should not emit CLI/runner default fields into the generated stub", () => {
		expect.assertions(3);

		const { fileSystem, volume } = createMemoryFileSystem();

		const project = makeResolvedProject({
			displayName: "client",
			rojoMounts: [{ dataModelPath: "ReplicatedStorage/Client", fsPath: "out/Client" }],
		});

		generateProjectStubs({
			fileSystem,
			outputRoot: "/root",
			projects: [project],
			rootDirectory: "/root",
		});

		const content = volume.readFileSync("/root/out/Client/jest.config.luau", "utf8");

		expect(content).not.toContain("silent =");

		expect(content).not.toContain("verbose =");
		expect(content).not.toContain("passWithNoTests =");
	});

	it("should not emit root CLI/runner keys when explicitly set", () => {
		expect.assertions(4);

		const content = generateClientStub({
			gameOutput: "out.json",
			outputFile: "results.json",
			port: 4242,
		});

		expect(content).not.toContain("outputFile =");

		expect(content).not.toContain("gameOutput =");
		expect(content).not.toContain("port =");
		expect(content).not.toContain("rojoProject =");
	});

	it("should not emit global-only test keys when set", () => {
		expect.assertions(3);

		const content = generateClientStub({
			bail: true,
			testNamePattern: "foo",
			updateSnapshot: true,
		});

		expect(content).not.toContain("bail =");

		expect(content).not.toContain("testNamePattern =");
		expect(content).not.toContain("updateSnapshot =");
	});

	it("should not emit mount or host-only project values", () => {
		expect.assertions(3);

		const { fileSystem, volume } = createMemoryFileSystem();

		const config: ResolvedConfig = fromAny({
			...createResolvedConfig(),
			outDir: "wrong-out-dir",
			root: "wrong-runtime-root",
			rootDir: "/root",
			typecheck: { enabled: true },
		});

		const project = makeResolvedProject({
			config,
			rojoMounts: [{ dataModelPath: "ReplicatedStorage/Client", fsPath: "out/Client" }],
		});

		generateProjectStubs({
			fileSystem,
			outputRoot: "/root",
			projects: [project],
			rootDirectory: "/root",
		});

		const content = volume.readFileSync("/root/out/Client/jest.config.luau", "utf8");

		expect(content).not.toContain("wrong-out-dir");
		expect(content).not.toContain("wrong-runtime-root");
		expect(content).not.toContain("typecheck");
	});

	it("should not emit projectTimeout, which Jest does not know", () => {
		expect.assertions(1);

		const content = generateClientStub({
			projectTimeout: 30_000,
		});

		expect(content).not.toContain("projectTimeout");
	});

	it("should emit shared jest-passthrough keys when set", () => {
		expect.assertions(3);

		const content = generateClientStub({
			clearMocks: true,
			setupFiles: ["ReplicatedStorage/setup"],
			testTimeout: 9000,
		});

		expect(content).toContain("clearMocks = true");

		expect(content).toContain('setupFiles = { "ReplicatedStorage/setup" }');
		expect(content).toContain("testTimeout = 9000");
	});

	it("should route stubs to outputRoot when provided", () => {
		expect.assertions(2);

		const { fileSystem, volume } = createMemoryFileSystem();

		const project = makeResolvedProject({
			displayName: "client",
			rojoMounts: [{ dataModelPath: "ReplicatedStorage/Client", fsPath: "out/Client" }],
		});

		generateProjectStubs({
			fileSystem,
			outputRoot: "/cache/.jest-roblox/workspace/pkg",
			projects: [project],
			rootDirectory: "/root",
		});

		expect(
			volume.existsSync("/cache/.jest-roblox/workspace/pkg/out/Client/jest.config.luau"),
		).toBeTrue();

		// Source tree untouched.
		expect(volume.existsSync("/root/out/Client/jest.config.luau")).toBeFalse();
	});

	it("should reject absolute mount fsPath when outputRoot is provided", () => {
		expect.assertions(1);

		const { fileSystem } = createMemoryFileSystem();

		const project = makeResolvedProject({
			displayName: "evil",
			rojoMounts: [{ dataModelPath: "ReplicatedStorage/Evil", fsPath: "/abs/path" }],
		});

		expect(() => {
			generateProjectStubs({
				fileSystem,
				outputRoot: "/cache/.jest-roblox/workspace/pkg",
				projects: [project],
				rootDirectory: "/root",
			});
		}).toThrow("mount fsPath must be relative");
	});

	it("should write a stub at every mount when only some mounts hold a user config", () => {
		expect.assertions(3);

		const { fileSystem, volume } = createMemoryFileSystem({
			"/root/out/Client/jest.config.luau": "return {}",
			"/root/out/Server/spec.spec.luau": "",
		});

		const project = makeResolvedProject({
			displayName: "partial",
			rojoMounts: [
				{ dataModelPath: "ReplicatedStorage/Client", fsPath: "out/Client" },
				{ dataModelPath: "ServerScriptService/Server", fsPath: "out/Server" },
			],
		});

		generateProjectStubs({
			fileSystem,
			outputRoot: "/cache/.jest-roblox/workspace/pkg",
			projects: [project],
			rootDirectory: "/root",
		});

		expect(
			volume.readFileSync(
				"/cache/.jest-roblox/workspace/pkg/out/Client/jest.config.luau",
				"utf8",
			),
		).toStartWith(GENERATED);
		expect(
			volume.readFileSync(
				"/cache/.jest-roblox/workspace/pkg/out/Server/jest.config.luau",
				"utf8",
			),
		).toStartWith(GENERATED);
		expect(volume.readFileSync("/root/out/Client/jest.config.luau", "utf8")).toBe("return {}");
	});
});

describe("stub writing with multi-mount projects", () => {
	const friendsMounts = mountsAt("src/Client", "src/Server", "src/Shared");

	it("should write identical stubs at every mount", () => {
		expect.assertions(3);

		const { fileSystem, volume } = createMemoryFileSystem();

		writeStubs(fileSystem, [
			makeResolvedProject({ displayName: "friends", rojoMounts: friendsMounts }),
		]);

		const clientContent = volume.readFileSync("/root/src/Client/jest.config.luau", "utf8");

		const serverContent = volume.readFileSync("/root/src/Server/jest.config.luau", "utf8");
		const sharedContent = volume.readFileSync("/root/src/Shared/jest.config.luau", "utf8");

		expect(clientContent).toBe(serverContent);
		expect(serverContent).toBe(sharedContent);
		expect(clientContent).toContain('\tdisplayName = "friends",');
	});

	it("should skip writing when a user jest.config.lua exists at the output directory", () => {
		expect.assertions(2);

		const { fileSystem, volume } = createMemoryFileSystem({
			"/cache/src/Client/jest.config.lua": "-- user-authored\nreturn {}",
		});

		writeCacheStubs(fileSystem, [makeResolvedProject({ rojoMounts: mountsAt("src/Client") })]);

		expect(volume.readFileSync("/cache/src/Client/jest.config.lua", "utf8")).toBe(
			"-- user-authored\nreturn {}",
		);
		expect(volume.existsSync("/cache/src/Client/jest.config.luau")).toBeFalse();
	});

	it("should overwrite our own previously-generated stub on re-gen", () => {
		expect.assertions(1);

		const { fileSystem, volume } = createMemoryFileSystem({
			"/root/src/Client/jest.config.luau": `${GENERATED}-- old content\n`,
		});

		writeStubs(fileSystem, [
			makeResolvedProject({ displayName: "updated", rojoMounts: mountsAt("src/Client") }),
		]);

		expect(volume.readFileSync("/root/src/Client/jest.config.luau", "utf8")).toContain(
			'\tdisplayName = "updated",',
		);
	});

	it("should delete a HEADER-prefixed legacy jest.config.lua sibling when writing the .luau stub", () => {
		expect.assertions(2);

		const { fileSystem, volume } = createMemoryFileSystem({
			"/root/src/Client/jest.config.lua": `${GENERATED}return {}\n`,
		});

		writeStubs(fileSystem, [makeResolvedProject({ rojoMounts: mountsAt("src/Client") })]);

		expect(volume.existsSync("/root/src/Client/jest.config.luau")).toBeTrue();
		expect(volume.existsSync("/root/src/Client/jest.config.lua")).toBeFalse();
	});

	it("should preserve a user-authored jest.config.lua when no .luau stub is written", () => {
		expect.assertions(2);

		const { fileSystem, volume } = createMemoryFileSystem({
			"/root/src/Client/jest.config.lua": "-- user wrote this\nreturn {}",
		});

		writeStubs(fileSystem, [makeResolvedProject({ rojoMounts: mountsAt("src/Client") })]);

		expect(volume.existsSync("/root/src/Client/jest.config.luau")).toBeFalse();
		expect(volume.readFileSync("/root/src/Client/jest.config.lua", "utf8")).toBe(
			"-- user wrote this\nreturn {}",
		);
	});
});

describe("cleanLeftoverStubs containment guard", () => {
	it("should throw when mount fsPath is absolute (escape via root)", () => {
		expect.assertions(2);

		const { fileSystem, volume } = createMemoryFileSystem({
			"/tmp/outside/jest.config.luau": "-- Auto-generated by jest-roblox (do not edit)\n",
		});

		const project = makeResolvedProject({
			rojoMounts: [{ dataModelPath: "ReplicatedStorage/evil", fsPath: "/tmp/outside" }],
		});

		expect(() => {
			return cleanLeftoverStubs({ fileSystem, projects: [project], rootDirectory: "/root" });
		}).toThrow(/mount fsPath must be relative/);
		// Outside marker file MUST survive the failed cleanup.
		expect(volume.existsSync("/tmp/outside/jest.config.luau")).toBeTrue();
	});

	it("should throw when mount fsPath escapes root via parent segments", () => {
		expect.assertions(2);

		const { fileSystem, volume } = createMemoryFileSystem({
			"/other-package/jest.config.luau": "-- Auto-generated by jest-roblox (do not edit)\n",
		});

		const project = makeResolvedProject({
			rojoMounts: [{ dataModelPath: "ReplicatedStorage/escape", fsPath: "../other-package" }],
		});

		expect(() => {
			return cleanLeftoverStubs({ fileSystem, projects: [project], rootDirectory: "/root" });
		}).toThrow(/mount fsPath escapes root directory/);
		// Sibling-package marker file MUST survive.
		expect(volume.existsSync("/other-package/jest.config.luau")).toBeTrue();
	});
});

describe(cleanLeftoverStubs, () => {
	it("should delete only marker-bearing files at known mount paths, leave user files alone", () => {
		expect.assertions(4);

		const { fileSystem, volume } = createMemoryFileSystem({
			"/root/dummy": "",
		});

		writeStubs(fileSystem, [makeResolvedProject({ rojoMounts: mountsAt("out/Client") })]);
		// Seed: one user-authored file (no marker). volume.fromJSON replaces the
		// volume by default; write directly to keep the prior seed intact.
		volume.mkdirSync("/root/out/Shared", { recursive: true });
		volume.writeFileSync(
			"/root/out/Shared/jest.config.luau",
			"return { displayName = 'shared' }\n",
		);

		const projects: Array<ResolvedProjectConfig> = [
			makeResolvedProject({
				displayName: "client",
				rojoMounts: [{ dataModelPath: "ReplicatedStorage/Client", fsPath: "out/Client" }],
			}),
			makeResolvedProject({
				displayName: "shared",
				rojoMounts: [{ dataModelPath: "ReplicatedStorage/Shared", fsPath: "out/Shared" }],
			}),
		];

		const cleaned = cleanLeftoverStubs({ fileSystem, projects, rootDirectory: "/root" });

		expect(cleaned).toHaveLength(1);
		expect(cleaned[0]).toContain("Client");
		// Auto-stub deleted.
		expect(volume.existsSync("/root/out/Client/jest.config.luau")).toBeFalse();
		// User file untouched.
		expect(volume.existsSync("/root/out/Shared/jest.config.luau")).toBeTrue();
	});

	it("should reuse the resolved real root across multiple marker-bearing mounts", () => {
		// Two marker-bearing leftover stubs in one call exercise the
		// `realRoot` lazy-init's cached-return branch.
		expect.assertions(3);

		const { fileSystem, volume } = createMemoryFileSystem({ "/root/dummy": "" });

		writeStubs(fileSystem, [
			makeResolvedProject({ rojoMounts: mountsAt("out/Client", "out/Server") }),
		]);

		const projects: Array<ResolvedProjectConfig> = [
			makeResolvedProject({
				displayName: "client",
				rojoMounts: [{ dataModelPath: "ReplicatedStorage/Client", fsPath: "out/Client" }],
			}),
			makeResolvedProject({
				displayName: "server",
				rojoMounts: [{ dataModelPath: "ServerStorage/Server", fsPath: "out/Server" }],
			}),
		];

		const cleaned = cleanLeftoverStubs({ fileSystem, projects, rootDirectory: "/root" });

		expect(cleaned).toHaveLength(2);
		expect(volume.existsSync("/root/out/Client/jest.config.luau")).toBeFalse();
		expect(volume.existsSync("/root/out/Server/jest.config.luau")).toBeFalse();
	});
});

describe("generateProjectStubs with a user-authored config at a mount", () => {
	it("should write the evaluated project values in place of the user config", () => {
		expect.assertions(4);

		const userConfig = "return { displayName = 'user-authored', placeId = '1' }\n";
		const { fileSystem, volume } = createMemoryFileSystem({
			"/root/out/Shared/jest.config.luau": userConfig,
		});

		const project = makeResolvedProject({
			config: { ...createResolvedConfig(), placeId: "123", rootDir: "/root", testTimeout: 7 },
			displayName: "shared",
			rojoMounts: [{ dataModelPath: "ReplicatedStorage/Shared", fsPath: "out/Shared" }],
		});

		generateProjectStubs({
			fileSystem,
			outputRoot: "/root/.cache",
			projects: [project],
			rootDirectory: "/root",
		});

		const stub = volume.readFileSync("/root/.cache/out/Shared/jest.config.luau", "utf8");

		expect(stub).toContain('\tdisplayName = "shared",\n');
		expect(stub).toContain("\ttestTimeout = 7,\n");
		expect(stub).not.toContain("placeId");
		expect(volume.readFileSync("/root/out/Shared/jest.config.luau", "utf8")).toBe(userConfig);
	});
});

describe("cleanLeftoverStubs symlink-escape guard", () => {
	it("should throw when a mount directory is a symlink pointing outside root", () => {
		expect.assertions(2);

		const { fileSystem, volume } = createMemoryFileSystem();

		volume.mkdirSync("/root", { recursive: true });

		volume.mkdirSync("/outside/escaped", { recursive: true });
		volume.writeFileSync(
			"/outside/escaped/jest.config.luau",
			"-- Auto-generated by jest-roblox (do not edit)\n",
		);
		// In-root symlink whose target is outside the root.
		volume.symlinkSync("/outside/escaped", "/root/escaped");

		const project = makeResolvedProject({
			rojoMounts: [{ dataModelPath: "ReplicatedStorage/escaped", fsPath: "escaped" }],
		});

		expect(() => {
			return cleanLeftoverStubs({ fileSystem, projects: [project], rootDirectory: "/root" });
		}).toThrow(/resolves outside root via symlink/);
		// Out-of-root marker file survives.
		expect(volume.existsSync("/outside/escaped/jest.config.luau")).toBeTrue();
	});
});
