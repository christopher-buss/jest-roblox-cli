import { fromAny } from "@total-typescript/shoehorn";

import { describe, expect, it } from "vitest";

import { createMemoryFileSystem } from "#test/mocks/memory-file-system.ts";
import { createResolvedConfig } from "#test/mocks/resolved-config.ts";
import { makeResolvedProject } from "#test/mocks/spec-resolved-project.ts";
import type { FileSystem } from "../utils/file-system.ts";
import type { ResolvedProjectConfig } from "./projects.ts";
import type { ResolvedConfig } from "./schema.ts";
import { cleanLeftoverStubs, generateProjectStubs } from "./stubs.ts";

const GENERATED = "-- Auto-generated by jest-roblox (do not edit)\n";

function mountsAt(...fsPaths: Array<string>): ResolvedProjectConfig["rojoMounts"] {
	return fsPaths.map((fsPath) => ({ dataModelPath: `ReplicatedStorage/${fsPath}`, fsPath }));
}

function writeStubs(fileSystem: FileSystem, projects: Array<ResolvedProjectConfig>): void {
	generateProjectStubs({ fileSystem, outputRoot: undefined, projects, rootDirectory: "/root" });
}

function writeCacheStubs(fileSystem: FileSystem, projects: Array<ResolvedProjectConfig>): void {
	generateProjectStubs({ fileSystem, outputRoot: "/cache", projects, rootDirectory: "/root" });
}

const SPLIT_MOUNTS = [
	{ dataModelPath: "ReplicatedStorage/Client", fsPath: "src/Client" },
	{ dataModelPath: "ServerScriptService/Server", fsPath: "src/Server" },
];

function generateClientStub(overrides: Partial<ResolvedConfig>): string {
	const { fileSystem, volume } = createMemoryFileSystem();
	const project = makeResolvedProject({
		config: { ...createResolvedConfig(), rootDir: "/root", ...overrides },
		rojoMounts: [{ dataModelPath: "ReplicatedStorage/Client", fsPath: "out/Client" }],
	});

	generateProjectStubs({
		fileSystem,
		outputRoot: undefined,
		projects: [project],
		rootDirectory: "/root",
	});

	return String(volume.readFileSync("/root/out/Client/jest.config.luau", "utf8"));
}

describe("stub writing", () => {
	it("should write the stub at the mount path", () => {
		expect.assertions(1);

		const { fileSystem, volume } = createMemoryFileSystem();

		writeStubs(fileSystem, [makeResolvedProject({ displayName: "client" })]);

		const content = volume.readFileSync("/root/out/client/jest.config.luau", "utf8");

		expect(content).toContain('\tdisplayName = "client",');
	});

	it("should create parent directories if they don't exist", () => {
		expect.assertions(1);

		const { fileSystem, volume } = createMemoryFileSystem();

		writeStubs(fileSystem, [makeResolvedProject({ rojoMounts: mountsAt("deep/nested/dir") })]);

		expect(volume.existsSync("/root/deep/nested/dir/jest.config.luau")).toBeTrue();
	});

	it("should skip writing when jest.config.luau already exists at the output directory", () => {
		expect.assertions(1);

		const { fileSystem, volume } = createMemoryFileSystem({
			"/cache/out/client/jest.config.luau": "return {}",
		});

		writeCacheStubs(fileSystem, [makeResolvedProject({ displayName: "client" })]);

		expect(volume.readFileSync("/cache/out/client/jest.config.luau", "utf8")).toBe("return {}");
	});

	it("should write a stub at every mount of a project", () => {
		expect.assertions(2);

		const { fileSystem, volume } = createMemoryFileSystem();

		writeStubs(fileSystem, [
			makeResolvedProject({ rojoMounts: mountsAt("out/client", "out/server") }),
		]);

		expect(volume.existsSync("/root/out/client/jest.config.luau")).toBeTrue();

		expect(volume.existsSync("/root/out/server/jest.config.luau")).toBeTrue();
	});

	it("should write a stub for every project", () => {
		expect.assertions(2);

		const { fileSystem, volume } = createMemoryFileSystem();

		writeStubs(fileSystem, [
			makeResolvedProject({ displayName: "client", rojoMounts: mountsAt("out/client") }),
			makeResolvedProject({ displayName: "server", rojoMounts: mountsAt("out/server") }),
		]);

		const client = volume.readFileSync("/root/out/client/jest.config.luau", "utf8");

		const server = volume.readFileSync("/root/out/server/jest.config.luau", "utf8");

		expect(client).toContain('\tdisplayName = "client",');
		expect(server).toContain('\tdisplayName = "server",');
	});
});

