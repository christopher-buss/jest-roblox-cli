import { Buffer } from "node:buffer";
import path from "node:path";

import type { FileSystem } from "../utils/file-system.ts";
import { nodeFileSystem } from "../utils/file-system.ts";

export const HEADER = "-- Auto-generated by jest-roblox (do not edit)\n";

export const STUB_FILENAME = "jest.config.luau";

/**
 * Distinguishes own-stubs (safe to delete) from user-authored configs.
 * Reads only the first `HEADER.length` bytes — bounded I/O regardless of
 * file size. Used by workspace pre-flight cleanup and the coverage shadow
 * orphan-sweep to ensure neither ever removes a user's canonical config.
 *
 * @param filePath - Config file to check.
 * @param fileSystem - File system to read through.
 * @returns True when the file starts with `HEADER`; false on any read error.
 */
export function isGeneratedStub(
	filePath: string,
	fileSystem: FileSystem = nodeFileSystem,
): boolean {
	try {
		const fd = fileSystem.openSync(filePath, "r");
		try {
			const buffer = Buffer.alloc(HEADER.length);
			fileSystem.readSync(fd, buffer, 0, HEADER.length, 0);
			return buffer.toString("utf8") === HEADER;
		} finally {
			fileSystem.closeSync(fd);
		}
	} catch {
		// Defensive catch for unusual FS errors (permission denied,
		// EISDIR, etc.). Caller treats `false` as "not our stub".
		return false;
	}
}

export const LEGACY_LUA_FILENAME = "jest.config.lua";

/**
 * Both names rojo merges into one `jest.config` ModuleScript. The bake writes
 * only the `.luau`, but every sweep has to see the legacy `.lua` too, or an
 * upgraded shadow keeps a stub beside the one that replaced it.
 */
export const STUB_FILENAMES: ReadonlySet<string> = new Set([LEGACY_LUA_FILENAME, STUB_FILENAME]);

/**
 * True when the directory holds a `jest.config.luau` or `jest.config.lua` that
 * this CLI did not generate. A stub write never lands on one, and a Studio
 * run, which serves the user's own place, injects no stub beside one.
 *
 * @param directoryPath - Mount directory to check.
 * @param fileSystem - File system to read through.
 * @returns True when a user-authored config is present.
 */
export function hasUserAuthoredConfig(
	directoryPath: string,
	fileSystem: FileSystem = nodeFileSystem,
): boolean {
	// A `.luau` or legacy `.lua` may be either our generated stub or a
	// user-authored config; only the HEADER prefix distinguishes them.
	// Reuse `isGeneratedStub`'s bounded header-read so this detection
	// check stays cheap (a few bytes) and resilient — unusual FS errors
	// downgrade to "not user-authored" rather than throwing out of a
	// detection helper called from multiple cleanup/build paths.
	const luauPath = path.join(directoryPath, STUB_FILENAME);
	if (fileSystem.existsSync(luauPath) && !isGeneratedStub(luauPath, fileSystem)) {
		return true;
	}

	const luaPath = path.join(directoryPath, LEGACY_LUA_FILENAME);
	return fileSystem.existsSync(luaPath) && !isGeneratedStub(luaPath, fileSystem);
}

/**
 * Keep the mounts Rojo syncs no user-authored config into: the mounts that
 * need a runtime-injected stub.
 *
 * @template T - Mount shape.
 * @param options - Mounts, root directory and file system.
 * @param options.fileSystem - File system to read through.
 * @param options.mounts - Mounts to filter.
 * @param options.rootDirectory - Root directory the mount paths resolve against.
 * @returns The mounts without a user-authored config.
 */
export function mountsWithoutUserConfig<T extends { readonly fsPath: string }>({
	fileSystem,
	mounts,
	rootDirectory,
}: {
	readonly fileSystem: FileSystem;
	readonly mounts: ReadonlyArray<T>;
	readonly rootDirectory: string;
}): Array<T> {
	return mounts.filter((mount) => {
		return !hasUserAuthoredConfig(path.resolve(rootDirectory, mount.fsPath), fileSystem);
	});
}

/**
 * Rojo merges `jest.config.lua` and `jest.config.luau` into the same
 * ModuleScript name, so leaving an old generated `.lua` stub next to the
 * new `.luau` would cause a name collision after upgrade. Caller guarantees
 * (via `hasUserAuthoredConfig`) that any `.lua` present here is our own
 * HEADER-prefixed stub, not a user-authored file.
 *
 * @param fileSystem - File system to delete through.
 * @param directoryPath - Mount directory that may hold a legacy `.lua` stub.
 */
export function removeLegacyGeneratedStub(fileSystem: FileSystem, directoryPath: string): void {
	const legacyPath = path.join(directoryPath, LEGACY_LUA_FILENAME);
	if (fileSystem.existsSync(legacyPath)) {
		fileSystem.unlinkSync(legacyPath);
	}
}
